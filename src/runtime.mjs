import { captureProjectImages, captureVisual } from './visual.mjs';
import { sampleLogs } from './diagnostics.mjs';
import { hash, stable } from './util.mjs';

export const runtimeRequested = (config, options) => Boolean(options.fullReview || config.visual || config.logs.length);
const visualIncomplete = visual => ['partial', 'unassessed'].includes(visual.status);
const visualFinding = view => view.horizontalOverflow > 4 || view.pageErrors > 0 || view.consoleErrors > 0 || view.unnamedButtons > 0;

export function runtimeSatisfied(runtime, inventory) {
  if (!runtime) return true;
  return !visualIncomplete(runtime.visual) && !runtime.visual.captures.some(visualFinding) &&
    (runtime.projectImages ?? []).every(capture => capture.status === 'captured') &&
    runtime.logs.every(log => log.status === 'sampled' && log.errors === 0) &&
    runtime.commands.every(command => command.samples.every(sample => !sample.errors)) &&
    (!inventory.backendFiles || runtime.commands.some(command => command.samples.length));
}

export async function collectRuntime(result, executions, options) {
  if (!runtimeRequested(result.config, options)) return null;
  const visual = await captureVisual(result, options);
  const projectImages = await captureProjectImages(result, options);
  const logs = await sampleLogs(result.info, result.config.logs);
  const commands = executions.map(execution => ({
    name: execution.name, status: execution.status,
    samples: execution.attempts.map(attempt => ({ digest: attempt.outputDigest, truncated: attempt.outputTruncated, ...attempt.diagnostics }))
  }));
  const evidence = { visual, ...(projectImages.length ? { projectImages } : {}), logs, commands };
  return { ...evidence, digest: hash(stable({ source: result.report.inputDigest, ...evidence })) };
}

export function attachRuntime(report, runtime) {
  if (!runtime) return;
  report.runtime = runtime;
  const { visual, logs, commands } = runtime;
  const imagesIncomplete = runtime.projectImages?.some(capture => capture.status !== 'captured');
  const incomplete = visualIncomplete(visual) || imagesIncomplete || logs.some(log => log.status === 'unavailable');
  if (incomplete) {
    if (visualIncomplete(visual)) report.coverage.limitations.push(visual.reason);
    if (imagesIncomplete) report.coverage.limitations.push('A configured rendered PNG was absent, invalid or not regenerated by this run.');
    if (logs.some(log => log.status === 'unavailable')) report.coverage.limitations.push('A configured log could not be sampled.');
    if (report.status === 'no_supported_static_findings') report.status = 'partial';
  }
  if (!commands.some(command => command.samples.length) && report.inventory.backendFiles > 0) {
    report.coverage.limitations.push('Backend or service files were inventoried without executed project checks.');
  }
  const needsReview = visual.captures.some(visualFinding) ||
    logs.some(log => log.errors > 0) || commands.some(command => command.samples.some(sample => sample.errors > 0));
  if (needsReview && report.status === 'no_supported_static_findings') report.status = 'needs_review';
}

export function runtimeRegressed(before, after) {
  if (before?.projectImages?.some(previous => previous.status === 'captured' &&
    !after?.projectImages?.some(current => current.path === previous.path && current.status === 'captured'))) return true;
  const match = (a, b) => a.route === b.route && a.viewport === b.viewport && a.theme === b.theme;
  return before?.visual.captures.some(previous => {
    if (previous.status !== 'captured') return false;
    const current = after?.visual.captures.find(capture => match(previous, capture));
    return !current || current.status !== 'captured' || current.horizontalOverflow > previous.horizontalOverflow + 4 ||
      current.pageErrors > previous.pageErrors || current.consoleErrors > previous.consoleErrors ||
      current.failedResponses > previous.failedResponses || current.unnamedButtons > previous.unnamedButtons;
  }) || false;
}
