import { build } from 'esbuild';
import { mkdir, readFile, writeFile, readdir, chmod } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const directory = path.join(root, 'skills/sloppyai/scripts');
await mkdir(directory, { recursive: true });
const common = { bundle: true, platform: 'node', target: 'node22', format: 'esm', legalComments: 'eof', define: { __SLOPPYAI_BUNDLE__: 'true' }, logLevel: 'warning' };
const banner = '// Generated by npm run build. Edit src/ instead.\nimport { createRequire as sloppyaiRequire } from "node:module";\nconst require = sloppyaiRequire(import.meta.url);';
const result = await build({ ...common, entryPoints: [path.join(root, 'src/cli.mjs')], outfile: path.join(directory, 'sloppyai.mjs'), banner: { js: '#!/usr/bin/env node\n' + banner }, metafile: true });
await build({ ...common, entryPoints: [path.join(root, 'src/index.mjs')], outfile: path.join(directory, 'core.mjs'), banner: { js: banner } });
await chmod(path.join(directory, 'sloppyai.mjs'), 0o755);
const packageRoots = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const segments = input.split('/');
  const at = segments.lastIndexOf('node_modules');
  if (at < 0) continue;
  packageRoots.add(segments.slice(0, at + (segments[at + 1]?.startsWith('@') ? 3 : 2)).join('/'));
}
const licenses = ['# Bundled third-party licences', '', 'The following libraries are bundled in the portable JavaScript helpers.', 'Their notices accompany the skill so a copied installation remains self-contained.', ''];
for (const relative of [...packageRoots].sort()) {
  const packageRoot = path.resolve(root, relative);
  const pkg = JSON.parse(await readFile(path.join(packageRoot, 'package.json'), 'utf8'));
  licenses.push(`## ${pkg.name} ${pkg.version}`, '');
  const files = (await readdir(packageRoot)).filter(name => /^(?:licen[cs]e|copying|notice)(?:\.|$)/i.test(name));
  if (!files.length) throw new Error('Missing bundled licence for ' + pkg.name);
  for (const file of files) licenses.push(await readFile(path.join(packageRoot, file), 'utf8'), '');
}
await writeFile(path.join(directory, 'THIRD_PARTY_LICENSES.md'), licenses.join('\n').trimEnd() + '\n');
await import('./catalog.mjs');
console.log('Built portable CLI, library and bundled licence notices.');
