import assert from 'node:assert/strict';
import os from 'node:os';
import path from 'node:path';
import { mkdtemp, readdir, readFile, writeFile, rm } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { loadCatalog } from '../src/catalog.mjs';
import { pathToFileURL, fileURLToPath } from 'node:url';

const exec = promisify(execFile);
const root = fileURLToPath(new URL('../', import.meta.url));
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const archive = path.join(root, pkg.name.replace(/^@/, '').replace('/', '-') + '-' + pkg.version + '.tgz');
const temporary = await mkdtemp(path.join(os.tmpdir(), 'sloppyai-package-'));
try {
  assert.ok(process.env.npm_execpath, 'Run this check with npm run package:smoke');
  await exec(process.execPath, [process.env.npm_execpath, 'install', '--prefix', temporary, '--ignore-scripts', '--no-audit', '--no-fund', archive], { cwd: temporary });
  const installed = path.join(temporary, 'node_modules', ...pkg.name.split('/'));
  const installedPackage = JSON.parse(await readFile(path.join(installed, 'package.json'), 'utf8'));
  assert.equal(installedPackage.version, pkg.version);
  assert.ok(!Object.keys(installedPackage.dependencies || {}).length, 'The portable package has no runtime dependency installation');
  const library = await import(pathToFileURL(path.join(installed, 'skills/sloppyai/scripts/core.mjs')));
  assert.equal(library.VERSION, pkg.version);
  assert.equal((await library.loadCatalog()).digest, (await loadCatalog()).digest);
  const checklist = 'skills/sloppyai/references/release-review.md';
  assert.equal(await readFile(path.join(installed, checklist), 'utf8'), await readFile(path.join(root, checklist), 'utf8'));
  const matrix = await exec(process.execPath, [path.join(installed, 'skills/sloppyai/scripts/sloppyai.mjs'), 'checklist', '--json'], { cwd: temporary, maxBuffer: 2_000_000 });
  const unassessed = JSON.parse(matrix.stdout);
  assert.equal(unassessed.items.length, 196);
  assert.ok(unassessed.items.every(item => item.status === 'not_assessed' && item.evidence.length === 0));
  const artifact = path.join(temporary, 'fixture.html');
  await writeFile(artifact, '<!doctype html><html lang="en"><body><h1>Export your report</h1><button>Save report</button></body></html>');
  const { stdout } = await exec(process.execPath, [path.join(installed, 'skills/sloppyai/scripts/sloppyai.mjs'), 'audit', artifact, '--json', '--no-save'], { cwd: temporary });
  const report = JSON.parse(stdout);
  assert.equal(report.coverage.assessedFiles, 1);
  assert.equal(report.findings.length, 0);
  const copy = path.join(temporary, 'generated.tsx');
  await writeFile(copy, 'export const Hero = () => <h1>One model drafts. Another reviews.</h1>;');
  const scanned = await exec(process.execPath, [path.join(installed, 'skills/sloppyai/scripts/sloppyai.mjs'), 'audit', copy, '--json', '--no-save'], { cwd: temporary });
  assert.ok(JSON.parse(scanned.stdout).findings.some(item => item.ruleId === 'C08' && item.location.line === 1));
  const jsxImage = path.join(temporary, 'photo.jsx');
  await writeFile(jsxImage, 'export const Photo = () => <img src="cover.png" />;');
  const imageScan = await exec(process.execPath, [path.join(installed, 'skills/sloppyai/scripts/sloppyai.mjs'), 'audit', jsxImage, '--json', '--no-save'], { cwd: temporary });
  assert.ok(JSON.parse(imageScan.stdout).findings.some(item => item.ruleId === 'A02' && item.location.line === 1));
  const planned = await exec(process.execPath, [path.join(installed, 'skills/sloppyai/scripts/sloppyai.mjs'), 'plan', jsxImage, '--json', '--no-save'], { cwd: temporary });
  const { guidance } = JSON.parse(planned.stdout);
  assert.ok(guidance.steps.some(step => step.ruleId === 'A02' && step.method === 'contextual' && step.verification.length));
  assert.ok((await readFile(guidance.repairGuideFile, 'utf8')).includes('Repair by problem'));
  assert.equal(await readFile(guidance.checklistFile, 'utf8'), await readFile(path.join(root, checklist), 'utf8'));
  assert.equal(guidance.designReview.criteria.length, 8);
  assert.equal(guidance.designReview.referencePolicy.use, 'quality');
  assert.equal(guidance.designReview.qualityWorkflow.status, 'not_assessed');
  assert.equal(await readFile(guidance.designReview.qualityWorkflow.guideFile, 'utf8'), await readFile(path.join(root, 'skills/sloppyai/references/quality-benchmarks.md'), 'utf8'));
  assert.equal(await readFile(guidance.designReview.qualityWorkflow.decisionGuideFile, 'utf8'), await readFile(path.join(root, 'skills/sloppyai/references/design-decisions.md'), 'utf8'));
  assert.equal(await readFile(guidance.designReview.qualityWorkflow.identityGuideFile, 'utf8'), await readFile(path.join(root, 'skills/sloppyai/references/product-identity.md'), 'utf8'));
  assert.equal(await readFile(guidance.designReview.qualityWorkflow.identityResetGuideFile, 'utf8'), await readFile(path.join(root, 'skills/sloppyai/references/identity-reset.md'), 'utf8'));
  assert.equal(await readFile(guidance.designReview.qualityWorkflow.landingPageGuideFile, 'utf8'), await readFile(path.join(root, 'skills/sloppyai/references/landing-pages.md'), 'utf8'));
  assert.ok(guidance.designReview.qualityWorkflow.checks.some(item => item.id === 'surface_purpose_and_story'));
  assert.ok(guidance.designReview.qualityWorkflow.checks.some(item => item.id === 'alternative_independence'));
  assert.ok(guidance.designReview.qualityWorkflow.checks.some(item => item.id === 'type_and_control_language'));
  assert.ok(guidance.designReview.qualityWorkflow.checks.some(item => item.id === 'proportion_and_familiarity'));
  assert.ok(guidance.designReview.qualityWorkflow.checks.some(item => item.id === 'identity_acceptance'));
  assert.ok(guidance.designReview.criteria.every(item => item.status === 'not_assessed' && item.score === null));
  assert.equal(guidance.designReview.changeContract.scope, 'refine');
  assert.equal(guidance.designReview.changeContract.explicit, false);
  const briefFile = path.join(temporary, 'design-brief.json');
  const designBrief = { changeScope: 'restore', preferredDirection: 'The preferred warm introduction', requestedChanges: ['Restore the earlier composition'], preserve: ['Product facts and working controls'] };
  await writeFile(briefFile, JSON.stringify({ designBrief }));
  const scoped = await exec(process.execPath, [path.join(installed, 'skills/sloppyai/scripts/sloppyai.mjs'), 'plan', artifact, '--config', briefFile, '--json', '--no-save'], { cwd: temporary });
  const portable = JSON.parse(scoped.stdout);
  assert.equal(portable.guidance.designReview.changeContract.scope, 'restore');
  assert.equal(portable.guidance.designReview.changeContract.explicit, true);
  assert.equal(portable.guidance.designReview.changeContract.preferredDirection, designBrief.preferredDirection);
  assert.deepEqual(portable.guidance.designReview.changeContract.requestedChanges, designBrief.requestedChanges);
  assert.equal(portable.guidance.designReview.changeContract.status, 'not_assessed');
  assert.deepEqual(portable.guidance.designReview.changeContract.evidence, []);
  assert.ok(portable.plan.includes(designBrief.preferredDirection));
  assert.equal(await readFile(guidance.designReview.guideFile, 'utf8'), await readFile(path.join(root, 'skills/sloppyai/references/visual-quality.md'), 'utf8'));
  assert.ok(!(await readdir(installed)).includes('src'), 'The installed bundle must work without development source');
  console.log('Packaged CLI, catalogue and library work from an isolated installation.');
} finally {
  await rm(temporary, { recursive: true, force: true });
}
